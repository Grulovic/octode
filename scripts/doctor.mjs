import { existsSync, readFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
let failed = false;
function report(ok, title, detail) {
  console.log(
    `${ok ? "PASS" : "FAIL"}  ${title}${detail ? ` — ${detail}` : ""}`,
  );
  if (!ok) failed = true;
}
function versionAtLeast(value, minimum) {
  const actual = value.split(".").map(Number);
  return (
    actual.some(
      (part, index) =>
        part > minimum[index] &&
        actual
          .slice(0, index)
          .every((earlier, position) => earlier === minimum[position]),
    ) || minimum.every((part, index) => actual[index] === part)
  );
}
function commandVersion(command, args) {
  const result = spawnSync(command, args, { encoding: "utf8", timeout: 10000 });
  return result.status === 0 ? result.stdout.trim() : null;
}

console.log("Octode desktop development readiness\n");
report(
  versionAtLeast(process.versions.node, [20, 19, 0]),
  "Node.js",
  `${process.versions.node}; requires 20.19+`,
);
const rust = commandVersion("rustc", ["--version"]);
report(
  Boolean(
    rust &&
      versionAtLeast(rust.match(/\d+\.\d+\.\d+/)?.[0] ?? "0.0.0", [1, 90, 0]),
  ),
  "Rust",
  `${rust ?? "not installed"}; requires 1.90+`,
);
report(
  Boolean(commandVersion("cargo", ["--version"])),
  "Cargo",
  commandVersion("cargo", ["--version"]) ?? "not installed",
);
if (process.platform === "darwin")
  report(
    Boolean(commandVersion("xcode-select", ["-p"])),
    "Xcode Command Line Tools",
    commandVersion("xcode-select", ["-p"]) ?? "not installed",
  );
const manifest = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
const packages = Object.keys({
  ...manifest.dependencies,
  ...manifest.devDependencies,
});
const missing = packages.filter(
  (name) => !existsSync(join(root, "node_modules", name, "package.json")),
);
report(
  !missing.length,
  "npm dependencies",
  missing.length ? `${missing.length} missing; run npm install` : "installed",
);
report(
  existsSync(join(root, "package-lock.json")),
  "npm lockfile",
  "generated by a successful npm install",
);
report(
  existsSync(join(root, "src-tauri/Cargo.lock")),
  "Cargo lockfile",
  "generated by a successful cargo check",
);
console.log("\nFor a normal terminal with network access:");
console.log("  1. Select Node 20.19+ (for this machine: nvm use 20.20.2).");
console.log(
  "  2. Install/select Rust 1.90+ using your existing Rust package manager.",
);
console.log("  3. npm install");
console.log("  4. npm run build && npm test && npm run test:native-core");
console.log("  5. cargo check --manifest-path src-tauri/Cargo.toml");
console.log("  6. npm run desktop");
console.log(
  "\nThis checks development prerequisites only, not native runtime behavior.",
);
process.exitCode = failed ? 1 : 0;
